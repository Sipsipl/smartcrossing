    ("sehen.html", "Was sieht ein Auto?"),
    ("tun.html", "Was kann es tun?"),
    ("gehirn.html", "Das Gehirn"),
    ("lernen.html", "Wie lernen sie?"),
    ("vergleich.html", "Vergleich"),
